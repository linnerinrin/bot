"""
img_draw.py 绘图模块

paste_me() 在所有图片下方绘制页脚 输入卡片尺寸定位
draw_song_card() 绘制单曲信息
create_score_card() 用于后续绘制成绩列表的单曲卡片
paste_single 统一create_score_card卡片的尺寸
"""

from PIL import Image, ImageDraw, ImageFont

from config.wmc_setting import wmc_settings
from nonebot import get_driver
from core.wmc_core.db_song import search_song, extra
from core.wmc_core.img_cover import get_cover_image
from core.wmc_core.img_material import version_title_load, dx_load, sss_load, star_load, fc_load, fdx_load
from utils.draw_text_center import draw_text_center
from utils.set_blur_to_image import set_blur_to_image

config = get_driver().config
botname = next(iter(config.nickname))


def paste_me(draw, size, fontsize=12):
    font = ImageFont.truetype(wmc_settings.FONT_PATH, fontsize)
    w, h = size
    draw_text_center(
        draw, f"Designed by Rei / Generated by {botname}", font,
        (w / 2 - 20, h - int(fontsize / 2) - int(h / 60), w / 2 + 20, h - int(fontsize / 2) - int(h / 60))
    )


def draw_song_card(song):
    ver = song['版本']
    ver = wmc_settings.VERSION_PNG[ver]
    ver_bg = Image.open(wmc_settings.WMC_MATERIAL_BG + f"{ver}")
    img = set_blur_to_image(ver_bg)
    draw = ImageDraw.Draw(img)

    font_title = ImageFont.truetype(wmc_settings.FONT_PATH, 28)
    font_normal = ImageFont.truetype(wmc_settings.FONT_PATH, 16)
    font_small = ImageFont.truetype(wmc_settings.FONT_PATH, 12)

    draw.rectangle([30, 30, wmc_settings.CANVAS_W - 30, 230], outline=wmc_settings.LINE_COLOR, width=2)

    cover_img = get_cover_image(song["索引"])
    img.paste(cover_img, (40, 40))

    draw.text((220, 40), f"{song['曲名']}", fill=wmc_settings.TEXT_COLOR, font=font_title)
    draw.text((220, 80), f"{song['曲师']}", fill=wmc_settings.TEXT_COLOR, font=font_normal)
    draw.text((220, 110), f"BPM：{song['BPM']}", fill=wmc_settings.TEXT_COLOR, font=font_normal)
    draw.text((220, 140), f"ID: {song['internalId']}", fill=wmc_settings.TEXT_COLOR, font=font_normal)
    draw.text((340, 110), f"版本：{song['版本']}", fill=wmc_settings.TEXT_COLOR, font=font_normal)
    draw.text((340, 140), f"分类：{song['分类']}", fill=wmc_settings.TEXT_COLOR, font=font_normal)

    version_title = version_title_load(song['版本'])
    img.paste(version_title, (wmc_settings.CANVAS_W - 200, 150), mask=version_title)

    is_dx = dx_load(song['类型'])
    img.paste(is_dx, (220, 170), mask=is_dx)

    draw.text((220, 200), f"JP: {song['JP']}", fill=wmc_settings.TEXT_COLOR, font=font_normal)
    draw.text((280, 200), f"INT: {song['INT']}", fill=wmc_settings.TEXT_COLOR, font=font_normal)
    draw.text((340, 200), f"USA: {song['USA']}", fill=wmc_settings.TEXT_COLOR, font=font_normal)
    draw.text((400, 200), f"CN: {song['CN']}", fill=wmc_settings.TEXT_COLOR, font=font_normal)

    draw.rectangle([30, 240, wmc_settings.CANVAS_W - 30, wmc_settings.CANVAS_H - 30], outline=wmc_settings.LINE_COLOR, width=2)

    y_start = 260
    x_start = 50
    col_width = 120
    row_height = 30

    diffs = ["BASIC", "ADV", "EXP", "MST", "REM"]
    diff_names = ["BSC", "ADV", "EXP", "MST", "REM"]
    x = x_start
    for i, name in enumerate(diff_names):
        draw.text((x + 10 + col_width, y_start), name, fill=wmc_settings.DIFF_COLOR[i], font=font_normal)
        x += col_width
    draw.line([x_start, y_start + 25, wmc_settings.CANVAS_W - 50, y_start + 25], fill=wmc_settings.LINE_COLOR, width=1)
    y = y_start + row_height

    rows = [
        ("Level", lambda d: f"{song[f'{d}_定数']}"),
        ("Tap", lambda d: f"{song[f'{d}_TAP']}"),
        ("Hold", lambda d: f"{song[f'{d}_HOLD']}"),
        ("Slide", lambda d: f"{song[f'{d}_SLIDE']}"),
        ("Touch", lambda d: f"{song[f'{d}_TOUCH']}"),
        ("Break", lambda d: f"{song[f'{d}_BREAK']}"),
        ("Total", lambda d: f"{song[f'{d}_TOTAL']}"),
        ("Designer", lambda d: f"{song[f'{d}_谱师']}" if d in ["EXP", "MST", "REM"] else ""),
    ]

    for label, get_val in rows:
        draw.text((x_start, y), label, fill=wmc_settings.TEXT_COLOR, font=font_normal)
        x = x_start + col_width
        for i, d in enumerate(diffs):
            val = get_val(d)
            if label == "Designer":
                if d == "BASIC" or d == "ADV":
                    continue
                draw.text((x + 10, y), val, fill=wmc_settings.DIFF_COLOR[i], font=font_normal)
                x += 1.5 * col_width
            else:
                draw.text((x + 10, y), val, fill=wmc_settings.DIFF_COLOR[i], font=font_normal)
                x += col_width
        draw.line([x_start, y + 25, wmc_settings.CANVAS_W - 50, y + 25], fill=wmc_settings.LINE_COLOR, width=1)
        y += row_height
    paste_me(draw, (800, 600))
    return img


def create_score_card(
    title: str,
    achieve: float,
    ds: float,
    rt: int,
    dx: int,
    id: int,
    ev: str,
    isfc: str,
    isfdx: str,
    card_width: int = 900,
    card_height: int = 450,
    radius: int = 45,
    dif: int = 3,
) -> Image.Image:
    font_big = ImageFont.truetype(wmc_settings.FONT_PATH, 72)
    font_mid = ImageFont.truetype(wmc_settings.FONT_PATH, 45)
    font_small = ImageFont.truetype(wmc_settings.FONT_PATH, 40)

    dif_key = next(k for k, v in wmc_settings.DIFF_INDEX.items() if v == dif)
    try:
        info = search_song(str(id))[0]
    except:
        try:
            info = search_song(extra[str(id)])[0]
        except:
            info = search_song("INTERNET YAMERO")[0]

    cover = get_cover_image(info["索引"])
    fulldx = int(info[f"{dif_key}_TOTAL"]) * 3

    ratio = dx / fulldx
    if ratio < 0.85:
        star = 0
    elif ratio < 0.90:
        star = 1
    elif ratio < 0.95:
        star = 2
    elif ratio < 0.97:
        star = 3
    elif ratio < 0.99:
        star = 4
    elif ratio < 0.995:
        star = 5
    else:
        star = 6

    isdx = "std" if int(id) < 10000 else "dx"
    isdx_pic = dx_load(isdx).resize((210, 75))

    ev_pic = sss_load(ev).resize((250, 105))

    try:
        fc_pic = fc_load(isfc).resize((150, 150))
    except:
        fc_pic = None
    try:
        fdx_pic = fdx_load(isfdx).resize((150, 150))
    except:
        fdx_pic = None

    if 0 < star < 3:
        star_pic = star_load(1)
    elif 2 < star < 5:
        star_pic = star_load(2)
    else:
        star_pic = star_load(3)
    star_pic = star_pic.resize((56, 56))

    card = Image.new("RGBA", (900, 450), (0, 0, 0, 0))
    draw = ImageDraw.Draw(card)
    w, h = card_width, card_height

    bg = set_blur_to_image(cover, (w, h))
    bg_box = (0, 0, w, h)
    bg = bg.convert("RGBA")
    mask = Image.new("L", (w, h), 0)
    mask_draw = ImageDraw.Draw(mask)
    mask_draw.rounded_rectangle([0, 0, w, h], radius=radius, fill=255, width=3)
    bg.putalpha(mask)
    card.paste(bg, bg_box[:2], mask=bg)

    cover_resize = cover.resize((300, 300))
    card.paste(cover_resize, (25, 25))

    text_x = 350
    text_y = 20
    draw.rounded_rectangle(
        [text_x - 15, text_y - 10, w - 20, text_y + 80],
        radius=radius, outline=wmc_settings.DIFF_COLOR[wmc_settings.DIFF_INDEX[dif_key]],
        fill=wmc_settings.DIFF_COLOR[wmc_settings.DIFF_INDEX[dif_key]], width=3
    )
    draw.text((text_x, text_y), title, font=font_mid, fill="white")
    draw_text_center(draw, str(id), font_mid, (text_x - 280, text_y + 370, text_x - 80, text_y + 370))
    card.paste(isdx_pic, (text_x - 280, text_y + 280), mask=isdx_pic)
    draw.text((text_x - 5, text_y + 70), f"{achieve:.4f}%", font=font_big, fill="white")
    draw.text((text_x, text_y + 160), str(ds) + "->" + str(rt), font=font_mid, fill="white")
    draw.text((text_x, text_y + 220), f"{dx}/{fulldx}", font=font_mid, fill="white")

    card.paste(ev_pic, (text_x - 20, text_y + 300), mask=ev_pic)
    star_x = text_x
    for epc in range(star):
        card.paste(star_pic, (star_x + 260, text_y + 190), mask=star_pic)
        star_x += 50
    if fc_pic:
        card.paste(fc_pic, (text_x + 230, text_y + 280), mask=fc_pic)
    if fdx_pic:
        card.paste(fdx_pic, (text_x + 380, text_y + 280), mask=fdx_pic)

    return card


def paste_single(single):
    search_song(f"{single['song_id']}")
    score_card = create_score_card(
        title=single["title"],
        achieve=single["achievements"],
        ds=single["ds"],
        rt=single["ra"],
        dx=single["dxScore"],
        id=single["song_id"],
        ev=single["rate"],
        isfc=single["fc"],
        isfdx=single["fs"],
        dif=single["level_index"]
    )
    return score_card.resize((300, 150)).convert("RGBA")


